-- ============================================================================
-- OlivePress - V1 : schema initial
-- Portable H2 (MODE=PostgreSQL) et PostgreSQL 14+.
-- Correspond aux entites JPA du package com.olivepress.domain.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Utilisateurs, permissions
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(60)  NOT NULL,
    email         VARCHAR(120) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    phone         VARCHAR(30),
    role          VARCHAR(20)  NOT NULL,
    active        BOOLEAN      NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email    UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS user_permissions (
    user_id    BIGINT      NOT NULL,
    permission VARCHAR(40) NOT NULL,
    CONSTRAINT fk_user_permissions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- Clients
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS clients (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(20) UNIQUE,
    first_name VARCHAR(80)  NOT NULL,
    last_name  VARCHAR(80)  NOT NULL,
    phone      VARCHAR(30)  NOT NULL,
    address    VARCHAR(255),
    active     BOOLEAN      NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- ---------------------------------------------------------------------------
-- Apports + historique de statut
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS apports (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero          VARCHAR(30)  NOT NULL,
    client_id       BIGINT       NOT NULL,
    received_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    gross_weight_kg NUMERIC(12,3) NOT NULL,
    tare_kg         NUMERIC(12,3) NOT NULL,
    net_weight_kg   NUMERIC(12,3) NOT NULL,
    ticket_number   VARCHAR(40),
    observations    VARCHAR(500),
    employee_id     BIGINT,
    status          VARCHAR(30)  NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_apports_numero   UNIQUE (numero),
    CONSTRAINT fk_apports_client   FOREIGN KEY (client_id)   REFERENCES clients (id),
    CONSTRAINT fk_apports_employee FOREIGN KEY (employee_id) REFERENCES users (id)
);
CREATE INDEX IF NOT EXISTS idx_apports_client ON apports (client_id);
CREATE INDEX IF NOT EXISTS idx_apports_status ON apports (status);
CREATE INDEX IF NOT EXISTS idx_apports_date   ON apports (received_at);

CREATE TABLE IF NOT EXISTS apport_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apport_id   BIGINT      NOT NULL,
    from_status VARCHAR(30),
    to_status   VARCHAR(30) NOT NULL,
    user_id     BIGINT,
    changed_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    comment     VARCHAR(300),
    CONSTRAINT fk_ash_apport FOREIGN KEY (apport_id) REFERENCES apports (id) ON DELETE CASCADE,
    CONSTRAINT fk_ash_user   FOREIGN KEY (user_id)  REFERENCES users (id)
);

-- ---------------------------------------------------------------------------
-- Production (rendement)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS production_records (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apport_id           BIGINT       NOT NULL,
    olives_processed_kg NUMERIC(12,3) NOT NULL,
    oil_obtained_l      NUMERIC(12,3) NOT NULL,
    yield_percent       NUMERIC(8,3)  NOT NULL,
    production_date     DATE          NOT NULL,
    employee_id         BIGINT,
    notes               VARCHAR(500),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_production_apport   FOREIGN KEY (apport_id)   REFERENCES apports (id),
    CONSTRAINT fk_production_employee FOREIGN KEY (employee_id) REFERENCES users (id)
);

-- ---------------------------------------------------------------------------
-- Stock d'huile (mouvements)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stock_movements (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_type VARCHAR(20)  NOT NULL,
    quantityl     NUMERIC(12,3) NOT NULL,
    lot_number    VARCHAR(40),
    client_id     BIGINT,
    reason        VARCHAR(255),
    user_id       BIGINT,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_stock_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_stock_user   FOREIGN KEY (user_id)   REFERENCES users (id)
);
CREATE INDEX IF NOT EXISTS idx_stock_date ON stock_movements (created_at);

-- ---------------------------------------------------------------------------
-- Livraisons
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS deliveries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero       VARCHAR(30)   NOT NULL,
    client_id    BIGINT        NOT NULL,
    quantity_l   NUMERIC(12,3) NOT NULL,
    lot_number   VARCHAR(40),
    delivered_at TIMESTAMP WITH TIME ZONE NOT NULL,
    employee_id  BIGINT,
    observations VARCHAR(400),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_deliveries_numero   UNIQUE (numero),
    CONSTRAINT fk_deliveries_client   FOREIGN KEY (client_id)   REFERENCES clients (id),
    CONSTRAINT fk_deliveries_employee FOREIGN KEY (employee_id) REFERENCES users (id)
);

-- ---------------------------------------------------------------------------
-- Factures et paiements
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS invoices (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero       VARCHAR(30)   NOT NULL,
    client_id    BIGINT        NOT NULL,
    invoice_date DATE          NOT NULL,
    due_date     DATE,
    total_amount NUMERIC(12,2) NOT NULL,
    statut       VARCHAR(20)   NOT NULL,
    notes        VARCHAR(400),
    apport_id    BIGINT,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_invoices_numero UNIQUE (numero),
    CONSTRAINT fk_invoices_client FOREIGN KEY (client_id) REFERENCES clients (id)
);

CREATE TABLE IF NOT EXISTS invoice_lines (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT         NOT NULL,
    description VARCHAR(200)   NOT NULL,
    quantity    NUMERIC(12,3)  NOT NULL,
    unit_price  NUMERIC(12,2)  NOT NULL,
    total       NUMERIC(12,2)  NOT NULL,
    CONSTRAINT fk_invoice_lines_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS payments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT         NOT NULL,
    amount      NUMERIC(12,2)  NOT NULL,
    mode        VARCHAR(20)    NOT NULL,
    reference   VARCHAR(60),
    paid_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    employee_id BIGINT,
    CONSTRAINT fk_payments_invoice  FOREIGN KEY (invoice_id)  REFERENCES invoices (id),
    CONSTRAINT fk_payments_employee FOREIGN KEY (employee_id) REFERENCES users (id)
);

-- ---------------------------------------------------------------------------
-- Notifications
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(120) NOT NULL,
    message     VARCHAR(400) NOT NULL,
    type        VARCHAR(30)  NOT NULL,
    user_id     BIGINT,
    read_flag   BOOLEAN      NOT NULL,
    entity_type VARCHAR(40),
    entity_id   BIGINT,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id)
);

-- ---------------------------------------------------------------------------
-- Journal d'audit
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT,
    action      VARCHAR(60)  NOT NULL,
    entity_type VARCHAR(40),
    entity_id   BIGINT,
    details     VARCHAR(1000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX IF NOT EXISTS idx_audit_date ON audit_logs (created_at);

-- ---------------------------------------------------------------------------
-- Parametres applicatifs (tarif de pressage, etc.)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS settings (
    setting_key   VARCHAR(60)  PRIMARY KEY,
    setting_value VARCHAR(200) NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
