-- ---------------------------------------------------------------------------
-- Utilisateurs, roles et permissions
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(60)  NOT NULL,
    email         VARCHAR(120) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    phone         VARCHAR(30),
    role          VARCHAR(20)  NOT NULL,          -- ADMIN | EMPLOYEE
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email    UNIQUE (email)
);

-- Permissions explicites d'un employe (les admins ont tout implicitement).
CREATE TABLE user_permissions (
    user_id    BIGINT      NOT NULL,
    permission VARCHAR(40) NOT NULL,
    CONSTRAINT fk_user_permissions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- Clients
-- ---------------------------------------------------------------------------
CREATE TABLE clients (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(20)  UNIQUE,              -- ex : CLI-00001
    first_name VARCHAR(80)  NOT NULL,
    last_name  VARCHAR(80)  NOT NULL,
    phone      VARCHAR(30)  NOT NULL,
    address    VARCHAR(255),
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Apports d'olives
-- ---------------------------------------------------------------------------
CREATE TABLE apports (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero          VARCHAR(30)  NOT NULL,        -- ex : AP-2026-000123
    client_id       BIGINT       NOT NULL,
    received_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    gross_weight_kg NUMERIC(12,3) NOT NULL,       -- poids brut (kg)
    tare_kg         NUMERIC(12,3) NOT NULL DEFAULT 0,
    net_weight_kg   NUMERIC(12,3) NOT NULL,       -- brut - tare
    ticket_number   VARCHAR(40),
    observations    VARCHAR(500),
    employee_id     BIGINT,                        -- agent ayant enregistre l'apport
    status          VARCHAR(30)  NOT NULL,         -- RECU | EN_ATTENTE | TRI | PRESSAGE | ...
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_apports_numero        UNIQUE (numero),
    CONSTRAINT fk_apports_client        FOREIGN KEY (client_id)   REFERENCES clients (id),
    CONSTRAINT fk_apports_employee      FOREIGN KEY (employee_id) REFERENCES users (id)
);
CREATE INDEX idx_apports_client ON apports (client_id);
CREATE INDEX idx_apports_status ON apports (status);
CREATE INDEX idx_apports_date   ON apports (received_at);

-- Historique des changements de statut d'un apport.
CREATE TABLE apport_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apport_id   BIGINT      NOT NULL,
    from_status VARCHAR(30),
    to_status   VARCHAR(30) NOT NULL,
    user_id     BIGINT,
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    comment     VARCHAR(300),
    CONSTRAINT fk_ash_apport FOREIGN KEY (apport_id) REFERENCES apports (id) ON DELETE CASCADE,
    CONSTRAINT fk_ash_user   FOREIGN KEY (user_id)  REFERENCES users (id)
);

-- ---------------------------------------------------------------------------
-- Production (rendement)
-- ---------------------------------------------------------------------------
CREATE TABLE production_records (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apport_id           BIGINT       NOT NULL,
    olives_processed_kg NUMERIC(12,3) NOT NULL,   -- olives reellement traitees
    oil_obtained_l      NUMERIC(12,3) NOT NULL,   -- huile obtenue (litres)
    yield_percent       NUMERIC(8,3)  NOT NULL,   -- = huile / olives * 100
    production_date     DATE          NOT NULL,
    employee_id         BIGINT,
    notes               VARCHAR(500),
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_production_apport  FOREIGN KEY (apport_id)  REFERENCES apports (id),
    CONSTRAINT fk_production_employee FOREIGN KEY (employee_id) REFERENCES users (id)
);

-- ---------------------------------------------------------------------------
-- Stock d'huile (mouvements)
-- ---------------------------------------------------------------------------
CREATE TABLE stock_movements (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_type VARCHAR(20)  NOT NULL,          -- ENTREE | SORTIE | AJUSTEMENT_POSITIF | AJUSTEMENT_NEGATIF
    quantity_l    NUMERIC(12,3) NOT NULL,         -- toujours positif ; le sens vient du type
    lot_number    VARCHAR(40),
    client_id     BIGINT,
    reason        VARCHAR(255),
    user_id       BIGINT,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_stock_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_stock_user   FOREIGN KEY (user_id)  REFERENCES users (id)
);
CREATE INDEX idx_stock_date ON stock_movements (created_at);

-- Stock disponible = SUM(signe du type * quantity_l) sur tous les mouvements.

-- ---------------------------------------------------------------------------
-- Livraisons
-- ---------------------------------------------------------------------------
CREATE TABLE deliveries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero       VARCHAR(30)   NOT NULL,          -- ex : LIV-2026-00002
    client_id    BIGINT        NOT NULL,
    quantity_l   NUMERIC(12,3) NOT NULL,
    lot_number   VARCHAR(40),
    delivered_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    employee_id  BIGINT,
    observations VARCHAR(400),
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_deliveries_numero   UNIQUE (numero),
    CONSTRAINT fk_deliveries_client   FOREIGN KEY (client_id)  REFERENCES clients (id),
    CONSTRAINT fk_deliveries_employee FOREIGN KEY (employee_id) REFERENCES users (id)
);

-- ---------------------------------------------------------------------------
-- Factures et paiements
-- ---------------------------------------------------------------------------
CREATE TABLE invoices (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero       VARCHAR(30)    NOT NULL,         -- ex : FAC-2026-00002
    client_id    BIGINT         NOT NULL,
    invoice_date DATE           NOT NULL,
    due_date     DATE,
    total_amount NUMERIC(12,2)  NOT NULL DEFAULT 0,  -- total TTC (DT)
    statut       VARCHAR(20)    NOT NULL,            -- IMPAYEE | PARTIELLE | PAYEE
    notes        VARCHAR(400),
    created_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uk_invoices_numero UNIQUE (numero),
    CONSTRAINT fk_invoices_client FOREIGN KEY (client_id) REFERENCES clients (id)
);

CREATE TABLE invoice_lines (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT         NOT NULL,
    description VARCHAR(200)   NOT NULL,
    quantity    NUMERIC(12,3)  NOT NULL,
    unit_price  NUMERIC(12,2)  NOT NULL,          -- prix unitaire TTC
    total       NUMERIC(12,2)  NOT NULL,          -- quantity * unit_price
    CONSTRAINT fk_invoice_lines_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE
);

CREATE TABLE payments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT         NOT NULL,
    amount      NUMERIC(12,2)  NOT NULL,
    mode        VARCHAR(20)    NOT NULL,          -- ESPECES | VIREMENT | CHEQUE | CARTE | AUTRE
    reference   VARCHAR(60),
    paid_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    employee_id BIGINT,
    CONSTRAINT fk_payments_invoice  FOREIGN KEY (invoice_id)  REFERENCES invoices (id),
    CONSTRAINT fk_payments_employee FOREIGN KEY (employee_id) REFERENCES users (id)
);

-- Paid amount = SUM(payments.amount) pour la facture ; reste = total_amount - paid.

-- ---------------------------------------------------------------------------
-- Notifications
-- ---------------------------------------------------------------------------
CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(120) NOT NULL,
    message     VARCHAR(400) NOT NULL,
    type        VARCHAR(30)  NOT NULL DEFAULT 'SYSTEME',
    user_id     BIGINT,                           -- NULL = tous les administrateurs
    read_flag   BOOLEAN      NOT NULL DEFAULT FALSE,
    entity_type VARCHAR(40),
    entity_id   BIGINT,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id)
);

-- ---------------------------------------------------------------------------
-- Journal d'audit (historique des actions)
-- ---------------------------------------------------------------------------
CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT,
    action      VARCHAR(60)  NOT NULL,
    entity_type VARCHAR(40),
    entity_id   BIGINT,
    details     VARCHAR(1000),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_audit_date ON audit_logs (created_at);
